# 直辖市 + 主要地级市/旅游城市白名单。
# 校验逻辑：城市名必须出现在这里，或者是某个已知城市（允许「苏州北」这类带后缀的输入）。
KNOWN_CITIES: set[str] = set()
for _cities in PROVINCE_CITIES.values():
    KNOWN_CITIES.update(_cities)


def normalize(raw: str) -> str:
    """清洗用户输入：去空白、去常见后缀、统一大小写。

    「苏州市」「苏州站」这类输入语义上是苏州，应归一化后再校验，
    否则用户会收到一句莫名其妙的「城市不存在」。
    """
    s = (raw or "").strip()
    # 去掉常见行政/站点后缀（注意顺序：先长后短，否则「苏州市」会被「市」先切掉一半）
    for suffix in ("特别行政区", "自治区", "自治州", "地区", "城市", "自治县",
                   "新区", "省", "市", "县", "区", "站"):
        if len(s) > len(suffix) and s.endswith(suffix):
            s = s[: -len(suffix)]
            break
    return s


def resolve(raw: str) -> dict:
    """识别输入是「有效城市」还是「省份」，都不是则判为无效。

    返回结构（供 API 直接透传给前端）：
        {"status": "ok",       "city": "苏州"}
        {"status": "province", "province": "江苏", "cities": ["南京", "苏州", ...]}
        {"status": "invalid",  "input": "asdf", "reason": "..."}
    """
    original = (raw or "").strip()
    if not original:
        return {"status": "invalid", "input": original, "reason": "城市名不能为空"}

    name = normalize(original)

    # 1) 省份（含全称与别名）—— 优先判断，因为「江苏」同时可能被当成城市名
    province = PROVINCE_ALIASES.get(original) or PROVINCE_ALIASES.get(name) or name
    if province in PROVINCE_CITIES:
        cities = PROVINCE_CITIES[province]
        # 直辖市只有自己一个「城市」，直接当城市用，不必让用户选
        if len(cities) == 1:
            return {"status": "ok", "city": cities[0]}
        # 「吉林」这类既是省名又是市名的输入：省份候选列表里就包含同名城市，
        # 所以照常返回候选让用户选即可——用户点「吉林」就等于选了吉林市。
        # 这里不做特殊处理，是为了保持行为一致、可预测。
        return {"status": "province", "province": province, "cities": cities}

    # 2) 已知城市
    if name in KNOWN_CITIES:
        return {"status": "ok", "city": name}

    # 3) 兜底启发式：能通过「中文 + 合理长度」检查的，放行给数据源判断。
    #    这不是宽容，而是必要的——内置表不可能穷举全国所有县市，
    #    若一律拒绝，用户查个小城市也会被误拦。真正的「不存在」由数据源
    #    （查不到车次/酒店）在下游暴露，那时会给出更准确的提示。
    if _looks_like_chinese_place(name):
        return {"status": "ok", "city": name, "unverified": True}

    return {
        "status": "invalid",
        "input": original,
        "reason": "无法识别的城市名，请填写中文城市名，例如：北京、苏州、成都",
    }


def _looks_like_chinese_place(name: str) -> bool:
    """粗判「是否像一个中文地名」。

    目的是拦住乱码（"asdfgh"、"@#$%"、"?????"），而不是做精确地理校验。
    规则：2-8 个字符，且全部是中文汉字。
    """
    if not (2 <= len(name) <= 8):
        return False
    return all("\u4e00" <= ch <= "\u9fff" for ch in name)
